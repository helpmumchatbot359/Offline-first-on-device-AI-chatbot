import 'package:objectbox/objectbox.dart';

@Entity() 
class ChatConversationEntity {
  @Id()
  int id = 0; 

  @Index()
  String chatId;     // Unique chat ID generated by mobile app (e.g., "user-uuid...")
  
  String messagesJson; // JSON string containing the list of messages, dates, and online/offline states

  ChatConversationEntity({
    this.id = 0,
    required this.chatId,
    required this.messagesJson,
  });
}