class SyncService {
  SyncService(
    this._apiClient,
    this._connectivity,
    this._localDataSource,
    this._diagnosticLogger, {
    required this._telemetry,
    required this._tokenStorage,
    required this._modelSetupService,
  });

  final ApiClient _apiClient;
  final Connectivity _connectivity;
  final ChatLocalDataSource _localDataSource;
  final DiagnosticLogger _diagnosticLogger;
  final TelemetryRecorder _telemetry;
  final TokenStorage _tokenStorage;
  final ModelSetupService _modelSetupService;

  StreamSubscription<List<ConnectivityResult>>? _subscription;
  bool _isSyncing = false;

  /// Heartbeat that retries the queue on its own.
  ///
  /// WHY: syncAll() used to run ONLY at app start and when the OS announced a
  /// connectivity CHANGE. If that one trigger was missed - the app was in the
  /// background, or checkConnectivity() still said "none" a second after Wi-Fi
  /// returned - the queued offline_inference events waited until the next app
  /// launch. On a phone that is never restarted, that means "telemetry never
  /// syncs". This timer makes the upload independent of connectivity events.
  Timer? _heartbeat;

  /// Every 60 s is cheap: syncAll() does nothing when the queues are empty.
  static const _heartbeatInterval = Duration(seconds: 60);

  /// Send telemetry in small batches so one upload is never huge,
  /// and an interrupted upload only has to repeat a small piece.
  static const _telemetryBatchSize = 50;
  static const _maxBatchesPerSync = 20;

  /// CloudFront sits in front of the API, and its WAF rule
  /// `SizeRestrictions_Body` refuses ANY request body larger than 8 KB with an
  /// HTML "403 Request blocked" page. That page is generated by CloudFront
  /// itself, so the request never reaches the backend — which is exactly why
  /// the diagnostics table stayed empty while the app was still uploading.
  ///
  /// 7,000 bytes leaves a safe margin for the JSON envelope. Anything bigger is
  /// split across several requests instead of being refused as one big body.
  @visibleForTesting
  static const maxUploadBodyBytes = 7000;

  /// Splits [items] so that `jsonEncode(buildBody(chunk))` stays under
  /// [maxBytes], keeping the original order.
  ///
  /// An item that is too large on its own is returned alone: the server can
  /// then reject just that item instead of blocking every good item behind it.
  @visibleForTesting
  static List<List<T>> chunkByJsonSize<T>(
    List<T> items,
    Object Function(List<T> chunk) buildBody, {
    int maxBytes = maxUploadBodyBytes,
  }) {
    final chunks = <List<T>>[];
    var current = <T>[];

    for (final item in items) {
      final candidate = [...current, item];
      final tooBig = current.isNotEmpty &&
          utf8.encode(jsonEncode(buildBody(candidate))).length > maxBytes;
      if (tooBig) {
        chunks.add(current);
        current = [item];
      } else {
        current = candidate;
      }
    }

    if (current.isNotEmpty) chunks.add(current);
    return chunks;
  }

  // What the network looked like last time we checked (to detect "online -> offline").
  List<ConnectivityResult>? _lastResults;
  // When the connection changed recently (to tell "intermittent" from "online").
  final List<DateTime> _recentChanges = [];

  // ---------------------------------------------------------------------------
  // Start listening to the network
  // ---------------------------------------------------------------------------
  void startBackgroundSync() {
    unawaited(_start());
    _heartbeat ??= Timer.periodic(_heartbeatInterval, (_) => unawaited(syncAll()));
  }

  Future<void> _start() async {
    try {
      _lastResults = await _connectivity.checkConnectivity();
    } catch (_) {}
    _subscription = _connectivity.onConnectivityChanged.listen(_onConnectivityChanged);
    unawaited(syncAll());
  }

  static bool _hasInternet(List<ConnectivityResult> r) => r.any((x) => x != ConnectivityResult.none);

  Future<void> _onConnectivityChanged(List<ConnectivityResult> results) async {
    final previous = _lastResults;
    final wasOnline = previous == null ? null : _hasInternet(previous);
    final isOnline = _hasInternet(results);
    _lastResults = results;

    // Only real changes count. (wifi -> cellular is not "offline".)
    if (wasOnline == isOnline) return;

    final changesBefore = _countRecentChanges();
    _recentChanges.add(DateTime.now());

    if (isOnline) {
      _diagnosticLogger.endOfflineCycle('reconnection', {'status': 'connected'});
      await syncAll();
    } else {
      _diagnosticLogger.startOfflineCycle('none');

      // THE moment for offline_started: it was available, now it is not.
      // `wasOnline == null` means we never knew the first state: not a change.
      if (wasOnline == true) {
        await _telemetry.recordOfflineStarted(
          chatId: await _safeActiveChatId(),
          modelVersion: await _safeModelVersion(),
          // 2+ changes in the last minute = a flickering connection.
          previousConnectivity: changesBefore >= 2 ? 'intermittent' : 'online',
          // The kind of network we just LOST.
          networkType: _networkTypeOf(previous ?? const []),
        );
      }
    }
  }

  int _countRecentChanges() {
    final cutoff = DateTime.now().subtract(const Duration(seconds: 60));
    _recentChanges.removeWhere((t) => t.isBefore(cutoff));
    return _recentChanges.length;
  }

  static String _networkTypeOf(List<ConnectivityResult> r) {
    if (r.contains(ConnectivityResult.wifi)) return 'wifi';
    if (r.contains(ConnectivityResult.mobile)) return 'cellular';
    return 'unknown';
  }

  Future<String?> _safeActiveChatId() async {
    try {
      return await _tokenStorage.activeChatId();
    } catch (_) {
      return null;
    }
  }

  Future<String?> _safeModelVersion() async {
    try {
      return await _modelSetupService.existingPath() != null ? TelemetryContract.modelVersion : null;
    } catch (_) {
      return null;
    }
  }

  Future<String> _connectivityLabel() async {
    try {
      final r = await _connectivity.checkConnectivity();
      if (!_hasInternet(r)) return 'offline';
      return _countRecentChanges() >= 2 ? 'intermittent' : 'online';
    } catch (_) {
      return 'unknown';
    }
  }

  // ---------------------------------------------------------------------------
  // Sync everything. Each part runs ON ITS OWN: if chat sync fails, telemetry
  // sync still runs (before, one failure stopped everything behind it).
  // ---------------------------------------------------------------------------
  Future<void> syncAll() async {
    if (_isSyncing) return;

    // No network = we do not even try, so nothing "failed" and no sync_error is made.
    try {
      if (!_hasInternet(await _connectivity.checkConnectivity())) return;
    } catch (_) {}

    _isSyncing = true;
    final stopwatch = Stopwatch()..start();
    try {
      // Each pipeline is isolated. Before, an exception inside the telemetry
      // step stopped the diagnostic step too, even though the comment above
      // promised they run on their own.
      final chatsOk = await _guardedSync('chat', _syncPendingChats);
      final telemetryOk = await _guardedSync('telemetry', _syncPendingTelemetry);
      final diagnosticsOk = await _guardedSync('diagnostic', _syncPendingDiagnostics);
      stopwatch.stop();
      _diagnosticLogger.logEvent(
        logType: 'synchronization_measurement',
        metrics: {
          'sync_success': chatsOk && telemetryOk && diagnosticsOk,
          'acknowledgement_time_ms': stopwatch.elapsedMilliseconds,
        },
      );
      // PROOF OF STATE: these two numbers are written to the diagnostics table
      // (which uploads successfully), so you can see from the backend exactly
      // what the phone still holds. pending > 0 means the event exists locally
      // but has not been acknowledged yet.
      final pending = await _localDataSource.countPendingTelemetry();
      final rejected = await _localDataSource.countTelemetryByState('rejected');
      _diagnosticLogger.logEvent(
        logType: 'telemetry_queue_state',
        metrics: {
          'pending_events': pending,
          'rejected_events': rejected,
          'telemetry_sync_ok': telemetryOk,
        },
      );
    } finally {
      _isSyncing = false;
    }
  }

  /// Runs one sync pipeline. A crash in one must never stop the others.
  Future<bool> _guardedSync(
    String name,
    Future<bool> Function() work,
  ) async {
    try {
      return await work();
    } catch (e) {
      debugPrint('SYNC PIPELINE "$name" FAILED: ${_describe(e)}');
      _diagnosticLogger.logEvent(
        logType: 'sync_pipeline_failed',
        metrics: {
          'sync_target': name,
          'error_message': _short(_describe(e)),
        },
      );
      return false;
    }
  }

  // ---------------------------------------------------------------------------
  // CHAT sync (logic unchanged, but a failure is now recorded as sync_error)
  // ---------------------------------------------------------------------------
  Future<bool> _syncPendingChats() async {
    final pending = await _localDataSource.getPendingMessages();
    if (pending.isEmpty) return true;

    final grouped = <String, List<Map<String, dynamic>>>{};
    final idsByChat = <String, List<int>>{};
    for (final msg in pending) {
      grouped.putIfAbsent(msg.chatId, () => []).add({
        'message': msg.message,
        'ai_response': msg.aiResponse,
        'date': msg.date,
      });
      idsByChat.putIfAbsent(msg.chatId, () => []).add(msg.id);
    }

    final clock = Stopwatch()..start();
    try {
      final response = await _apiClient.dio.post('/v1/chats/sync', data: grouped);
      if (_ok(response)) {
        for (final ids in idsByChat.values) {
          await _localDataSource.markMessagesAcknowledged(ids);
        }
      }
      return true;
    } catch (e) {
      clock.stop();
      final failure = classifySyncError(e);
      await _recordSyncError(
        target: 'chat',
        code: failure.code,
        status: failure.status,
        latencyMs: clock.elapsedMilliseconds,
        chatId: grouped.keys.first, // a chat that was in the failed batch
      );
      _diagnosticLogger.logEvent(logType: 'runtime_failure_detail', metrics: {
        'failure_type': 'sync_error',
        'error_message': _describe(e),
        'duration_ms': clock.elapsedMilliseconds,
      });
      return false;
    }
  }

  // ---------------------------------------------------------------------------
  // TELEMETRY sync
  //  * only events that follow the contract are sent
  //  * sent in small batches, oldest first
  //  * ONLY the UUIDs the backend sends back are marked as acknowledged
  //  * anything not acknowledged stays 'pending' and is retried with the SAME
  //    event_uuid, so an interrupted upload can never create duplicates
  // ---------------------------------------------------------------------------
  Future<bool> _syncPendingTelemetry() async {
    await _dropEventsTheBackendWouldReject();

    for (var round = 0; round < _maxBatchesPerSync; round++) {
      final batch = await _localDataSource.getPendingTelemetryEvents(limit: _telemetryBatchSize);
      if (batch.isEmpty) return true;

      // A batch of 50 events can easily exceed the 8 KB WAF limit even though
      // the count looks small. Split by the REAL encoded size.
      final chunks = chunkByJsonSize(
        batch,
        (events) => events.map(_toPayload).toList(),
      );

      for (final chunk in chunks) {
        final mayContinue = await _uploadTelemetryChunk(chunk);
        if (!mayContinue) return false;
      }
    }
    return true;
  }

  /// Uploads one size-limited telemetry chunk.
  ///
  /// Returns `false` when this sync run must stop (network/server problem), and
  /// `true` when the next chunk may be tried.
  Future<bool> _uploadTelemetryChunk(List<LocalTelemetryEvent> batch) async {
    final clock = Stopwatch()..start();
    final result = await _postTelemetry(batch);
    clock.stop();

    if (result.acknowledged.isNotEmpty) {
      await _localDataSource.markTelemetryAcknowledged(result.acknowledged.toList());
    }

    if (result.ok) {
      // PROOF OF DELIVERY: the server said 200 AND named every UUID it
      // stored. Seeing this record in the diagnostics table means the
      // telemetry row really reached the backend for this event_uuid.
      _diagnosticLogger.logEvent(
        logType: 'telemetry_upload_acknowledged',
        metrics: {
          'batch_size': batch.length,
          'event_types': batch.map((e) => e.eventType).toSet().toList(),
          'first_event_uuid': batch.first.eventUuid,
          'first_chat_id': batch.first.chatId,
        },
      );
      return true;
    }

    // A "permanent" answer (HTTP 400/413/422) usually means ONE event has a
    // field the server refuses. Before, that one event blocked the whole
    // batch and every good inference event behind it. Retry one-by-one.
    if (result.permanent) {
      final rejected = <int>[];
      for (final event in batch) {
        if (result.acknowledged.contains(event.eventUuid)) continue;

        final single = await _postTelemetry([event]);
        if (single.acknowledged.isNotEmpty) {
          await _localDataSource.markTelemetryAcknowledged(single.acknowledged.toList());
          continue;
        }
        if (!single.permanent) {
          // The isolating retry hit a network/server problem. Keep everything
          // pending and try again on the next sync.
          await _recordSyncError(
            target: 'telemetry',
            code: single.code,
            status: single.status,
            latencyMs: clock.elapsedMilliseconds,
          );
          return false;
        }

        rejected.add(event.id);
        _diagnosticLogger.logEvent(
          logType: 'telemetry_event_rejected_by_server',
          metrics: {
            'event_uuid': event.eventUuid,
            'event_type': event.eventType,
            'chat_id': event.chatId,
            'http_status': single.status,
            'server_response': _short(single.body),
            // The exact JSON we sent for THIS event, so the reason is
            // reproducible without another phone test.
            'payload_sent': _short(jsonEncode(_toPayload(event)), 1200),
          },
        );
      }

      // Quarantine the refused events so they stop blocking good ones.
      if (rejected.isNotEmpty) {
        await _localDataSource.markTelemetryRejected(rejected);
      }
      return true;
    }

    // 2xx without every acknowledgement, or a network/server problem.
    // Keep the events pending and stop this sync run.
    await _recordSyncError(
      target: 'telemetry',
      code: result.code,
      status: result.status,
      latencyMs: clock.elapsedMilliseconds,
    );
    _diagnosticLogger.logEvent(
      logType: 'telemetry_upload_not_acknowledged',
      metrics: {
        'batch_size': batch.length,
        'acknowledged_count': result.acknowledged.length,
        'http_status': result.status,
        'server_response': _short(result.body),
      },
    );
    return false;
  }

  /// Sends one telemetry batch and reports exactly what happened.
  ///
  /// [permanent] means the server refused the payload itself (4xx). In that
  /// case the caller retries each event alone, so one bad event cannot hide
  /// the good ones.
  Future<({
    bool ok,
    bool permanent,
    Set<String> acknowledged,
    int? status,
    Object? body,
    String code,
  })> _postTelemetry(List<LocalTelemetryEvent> batch) async {
    try {
      final response = await _apiClient.dio.post(
        '/v1/telemetry',
        data: batch.map(_toPayload).toList(),
      );

      final acknowledged = <String>{};
      final data = response.data;
      if (data is Map && data['acknowledged_event_uuids'] is List) {
        for (final uuid in data['acknowledged_event_uuids'] as List) {
          acknowledged.add(uuid.toString());
        }
      }

      // Only trust UUIDs that we really sent in THIS batch.
      final sent = batch.map((e) => e.eventUuid).toSet();
      final confirmed = acknowledged.intersection(sent);
      final ok = _ok(response) && confirmed.length == batch.length;

      return (
        ok: ok,
        permanent: false,
        acknowledged: confirmed,
        status: response.statusCode,
        body: data,
        code: 'SERVER_ERROR',
      );
    } on DioException catch (e) {
      final status = e.response?.statusCode;
      final permanent = status == 400 || status == 413 || status == 422;
      return (
        ok: false,
        permanent: permanent,
        acknowledged: <String>{},
        status: status,
        body: e.response?.data ?? e.message,
        code: classifySyncError(e).code,
      );
    } catch (e) {
      return (
        ok: false,
        permanent: false,
        acknowledged: <String>{},
        status: null,
        body: e.toString(),
        code: 'INVALID_PAYLOAD',
      );
    }
  }

  /// Exactly the JSON shape of the contract (section 4).
  ///
  /// IMPORTANT: optional fields are LEFT OUT when they have no value. Sending
  /// `"latency_ms": null` or `"error_code": null` looks harmless, but strict
  /// servers can reject the whole batch for it. The contract example for
  /// offline_started does not contain those keys at all.
  Map<String, dynamic> _toPayload(LocalTelemetryEvent e) => buildTelemetryPayload(e);

  /// Visible for tests: proves that optional null fields are never sent.
  @visibleForTesting
  static Map<String, dynamic> buildTelemetryPayload(LocalTelemetryEvent e) {
    final payload = <String, dynamic>{
      'event_uuid': e.eventUuid,
      'event_type': e.eventType,
      'date': e.date,
      'connectivity': e.connectivity,
      'metadata': _cleanMetadata(e.metadataJson),
    };
    if (e.chatId != null && e.chatId!.isNotEmpty) payload['chat_id'] = e.chatId;
    if (e.modelVersion != null) payload['model_version'] = e.modelVersion;
    if (e.latencyMs != null) payload['latency_ms'] = e.latencyMs;
    if (e.outcome != null) payload['outcome'] = e.outcome;
    if (e.errorCode != null) payload['error_code'] = e.errorCode;
    return payload;
  }

  /// Also protects events queued by an older build, which may still contain
  /// null metadata values.
  static Map<String, Object?> _cleanMetadata(String metadataJson) {
    try {
      final decoded = jsonDecode(metadataJson);
      if (decoded is! Map) return <String, Object?>{};
      return TelemetryRecorder.withoutNulls(
        decoded.map((key, value) => MapEntry(key.toString(), value)),
      );
    } catch (_) {
      return <String, Object?>{};
    }
  }

  /// SAFETY NET. Old events saved by the previous version of the app
  /// (event_type 'online_inference', error_code 'offline_mode', ...) can never
  /// be accepted. If they stay in the queue they are sent again and again and
  /// the backend refuses the WHOLE batch each time, so good events never arrive.
  /// This removes only the events that break the contract.
  Future<void> _dropEventsTheBackendWouldReject() async {
    final pending = await _localDataSource.getPendingTelemetryEvents();
    final badIds = <int>[];
    for (final e in pending) {
      final problems = TelemetryContract.validate(e);
      if (problems.isNotEmpty) {
        badIds.add(e.id);
        debugPrint('TELEMETRY DROPPED (${e.eventType}): $problems');
        _diagnosticLogger.logEvent(
          logType: 'telemetry_dropped_invalid',
          metrics: {
            'event_uuid': e.eventUuid,
            'event_type': e.eventType,
            'chat_id': e.chatId,
            'problems': problems,
          },
        );
      }
    }
    if (badIds.isEmpty) return;
    await _localDataSource.removeTelemetry(badIds);
    _diagnosticLogger.logEvent(
      logType: 'telemetry_dropped_invalid_total',
      metrics: {'count': badIds.length},
    );
  }

  Future<void> _recordSyncError({
    required String target, // chat | telemetry
    required String code,
    int? status,
    required int latencyMs,
    String? chatId,
  }) async {
    await _telemetry.recordSyncError(
      chatId: target == 'telemetry' ? null : chatId,
      latencyMs: latencyMs,
      errorCode: code,
      connectivity: await _connectivityLabel(),
      syncTarget: target,
      pendingChatCount: await _localDataSource.countPendingMessages(),
      pendingEventCount: await _localDataSource.countPendingTelemetry(),
      httpStatus: status,
    );
  }

  /// Turns "whatever went wrong" into ONE of the five codes in the contract.
  static ({String code, int? status}) classifySyncError(Object e) {
    if (e is DioException) {
      final status = e.response?.statusCode;
      if (status != null) {
        if (status == 401 || status == 403) return (code: 'UNAUTHORIZED', status: status);
        if (status == 400 || status == 413 || status == 422) {
          return (code: 'INVALID_PAYLOAD', status: status);
        }
        return (code: 'SERVER_ERROR', status: status);
      }
      switch (e.type) {
        case DioExceptionType.connectionTimeout:
        case DioExceptionType.sendTimeout:
        case DioExceptionType.receiveTimeout:
          return (code: 'SYNC_TIMEOUT', status: null);
        default:
          return (code: 'NETWORK_UNAVAILABLE', status: null);
      }
    }
    // Not a network problem: our own code failed while preparing the data.
    return (code: 'INVALID_PAYLOAD', status: null);
  }

  // ---------------------------------------------------------------------------
  // DIAGNOSTIC logs. NOTE: '/v1/diagnostic-logs' is NOT in the contract you
  // were sent. It now runs on its own, so if that endpoint does not exist it
  // can no longer disturb telemetry. Ask the backend engineer if he wants it.
  // ---------------------------------------------------------------------------
  Future<bool> _syncPendingDiagnostics() async {
    try {
      final pending = await _diagnosticLogger.readPending();
      if (pending.byCycle.isEmpty) return true;

      final totalRecords = pending.byCycle.values
          .fold<int>(0, (sum, records) => sum + records.length);
      debugPrint(
        'DIAGNOSTIC UPLOAD START: cycles=${pending.byCycle.length} '
        'records=$totalRecords maxBodyBytes=$maxUploadBodyBytes '
        'policy=chunked+waf-safe',
      );

      var allOk = true;
      for (final entry in pending.byCycle.entries) {
        // One offline cycle can contain dozens of records, each with the full
        // device/memory block. Sending them as one body is what crossed the
        // 8 KB WAF limit and produced the 403. Send size-limited chunks that
        // all belong to the same cycle.
        final chunks = chunkByJsonSize(
          entry.value,
          (records) => {'offline_cycle_id': entry.key, 'records': records},
        );

        for (final records in chunks) {
          final body = {'offline_cycle_id': entry.key, 'records': records};
          final bytes = utf8.encode(jsonEncode(body)).length;
          final types = records
              .map((record) => record['log_type'])
              .whereType<Object>()
              .toSet()
              .join('|');
          try {
            final response = await _apiClient.dio.post(
              '/v1/diagnostic-logs',
              data: body,
            );
            if (!_ok(response)) {
              allOk = false;
              debugPrint(
                'DIAGNOSTIC CHUNK REFUSED: cycle=${entry.key} '
                'records=${records.length} bytes=$bytes types=$types -> '
                '${response.statusCode}: ${_short(response.data)}',
              );
            }
          } on DioException catch (e) {
            // Dio throws for 4xx/5xx instead of returning the response. Catch
            // it per chunk so one refused record cannot hide every chunk after
            // it, and so the log shows the exact size that was rejected.
            allOk = false;
            debugPrint(
              'DIAGNOSTIC CHUNK REFUSED: cycle=${entry.key} '
              'records=${records.length} bytes=$bytes types=$types -> '
              '${e.response?.statusCode ?? e.type.name}: '
              '${_short(e.response?.data ?? e.message)}',
            );
          }
        }
      }
      // Only rename the files when EVERY chunk was accepted; otherwise the
      // records stay pending and are retried on the next sync.
      if (allOk) await _diagnosticLogger.markUploaded(pending.files);
      return allOk;
    } catch (e) {
      debugPrint('DIAGNOSTIC UPLOAD FAILED: ${_describe(e)}');
      return false;
    }
  }

  static String _describe(Object e) {
    if (e is DioException) {
      return '${e.requestOptions.method} ${e.requestOptions.path} -> '
          '${e.response?.statusCode ?? e.type.name}: ${e.response?.data ?? e.message}';
    }
    return e.toString();
  }

  /// Keeps a diagnostic record small even when the server returns a long error.
  static String _short(Object? value, [int max = 500]) {
    final text = value?.toString() ?? '';
    return text.length <= max ? text : '${text.substring(0, max)}...';
  }

  static bool _ok(Response r) => (r.statusCode ?? 0) >= 200 && (r.statusCode ?? 0) < 300;

  void stop() {
    _heartbeat?.cancel();
    _heartbeat = null;
    _subscription?.cancel();
  }
}